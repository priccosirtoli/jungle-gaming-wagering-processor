import { EntitySchema } from '@mikro-orm/core';

/*
 * Persistence records mapped with EntitySchema, so the domain classes stay free
 * of ORM decorators and types. Mappers convert between records and the domain.
 * Money columns are numeric(20,2) read as strings (DecimalType in string mode)
 * and turned into Money on rehydration, so no value ever passes through a float.
 */

const timestamptz = { type: 'datetime', columnType: 'timestamptz' } as const;
const money = { type: 'decimal', precision: 20, scale: 2 } as const;

export class WalletRecord {
  id!: string;
  playerId!: string;
  currency!: string;
  balance!: string;
  version!: number;
  createdAt!: Date;
  updatedAt!: Date;
}

export const WalletSchema = new EntitySchema<WalletRecord>({
  class: WalletRecord,
  tableName: 'wallets',
  properties: {
    id: { type: 'uuid', primary: true },
    playerId: { type: 'uuid' },
    currency: { type: 'string', columnType: 'char(3)' },
    balance: money,
    version: { type: 'integer' },
    createdAt: timestamptz,
    updatedAt: timestamptz,
  },
});

export class WagerTransactionRecord {
  id!: string;
  providerId!: string;
  externalTransactionId!: string;
  idempotencyKey!: string;
  payloadHash!: string;
  walletId!: string;
  playerId!: string;
  roundId!: string;
  gameId!: string;
  kind!: string;
  amount!: string;
  currency!: string;
  referenceExternalTransactionId?: string | null;
  referenceTransactionId?: string | null;
  status!: string;
  failureCode?: string | null;
  observedBalance?: string | null;
  createdAt!: Date;
  processedAt?: Date | null;
  updatedAt!: Date;
  /** Retry bookkeeping for PENDING_REFERENCE; persistence-only, not part of the domain state. */
  referenceAttempts!: number;
  nextReferenceAttemptAt?: Date | null;
}

export const WagerTransactionSchema = new EntitySchema<WagerTransactionRecord>({
  class: WagerTransactionRecord,
  tableName: 'wager_transactions',
  properties: {
    id: { type: 'uuid', primary: true },
    providerId: { type: 'text' },
    externalTransactionId: { type: 'text' },
    idempotencyKey: { type: 'text' },
    payloadHash: { type: 'string', columnType: 'char(64)' },
    walletId: { type: 'uuid' },
    playerId: { type: 'uuid' },
    roundId: { type: 'text' },
    gameId: { type: 'text' },
    kind: { type: 'text' },
    amount: money,
    currency: { type: 'string', columnType: 'char(3)' },
    referenceExternalTransactionId: { type: 'text', nullable: true },
    referenceTransactionId: { type: 'uuid', nullable: true },
    status: { type: 'text' },
    failureCode: { type: 'text', nullable: true },
    observedBalance: { ...money, nullable: true },
    createdAt: timestamptz,
    processedAt: { ...timestamptz, nullable: true },
    updatedAt: timestamptz,
    referenceAttempts: { type: 'integer' },
    nextReferenceAttemptAt: { ...timestamptz, nullable: true },
  },
});

/** Insert-only: the table rejects UPDATE/DELETE. `seq` is generated by Postgres and read with SQL. */
export class LedgerEntryRecord {
  id!: string;
  walletId!: string;
  transactionId!: string;
  direction!: string;
  amount!: string;
  currency!: string;
  balanceBefore!: string;
  balanceAfter!: string;
  createdAt!: Date;
}

export const LedgerEntrySchema = new EntitySchema<LedgerEntryRecord>({
  class: LedgerEntryRecord,
  tableName: 'wallet_ledger_entries',
  properties: {
    id: { type: 'uuid', primary: true },
    walletId: { type: 'uuid' },
    transactionId: { type: 'uuid' },
    direction: { type: 'text' },
    amount: money,
    currency: { type: 'string', columnType: 'char(3)' },
    balanceBefore: money,
    balanceAfter: money,
    createdAt: timestamptz,
  },
});

export class OutboxRecord {
  id!: string;
  aggregateId!: string;
  eventType!: string;
  payload!: Record<string, unknown>;
  occurredAt!: Date;
  attempts!: number;
  nextAttemptAt!: Date;
  publishedAt?: Date | null;
}

export const OutboxSchema = new EntitySchema<OutboxRecord>({
  class: OutboxRecord,
  tableName: 'outbox_messages',
  properties: {
    id: { type: 'uuid', primary: true },
    aggregateId: { type: 'uuid' },
    eventType: { type: 'text' },
    payload: { type: 'json', columnType: 'jsonb' },
    occurredAt: timestamptz,
    attempts: { type: 'integer' },
    nextAttemptAt: timestamptz,
    publishedAt: { ...timestamptz, nullable: true },
  },
});

export class InboxRecord {
  consumerName!: string;
  messageId!: string;
  payloadHash!: string;
  receivedAt!: Date;
  processedAt?: Date | null;
}

export const InboxSchema = new EntitySchema<InboxRecord>({
  class: InboxRecord,
  tableName: 'inbox_messages',
  properties: {
    consumerName: { type: 'text', primary: true },
    messageId: { type: 'text', primary: true },
    payloadHash: { type: 'string', columnType: 'char(64)' },
    receivedAt: timestamptz,
    processedAt: { ...timestamptz, nullable: true },
  },
});

export const entities = [WalletSchema, WagerTransactionSchema, LedgerEntrySchema, OutboxSchema, InboxSchema];
